public class typesofoperators {
    public static void main(String[] args) {
        int A = 10;
        int B = 5;
        int Add = A + B;
        int Sub = A - B;
        int Mult = A * B;
        int Div = A / B;
        int Mod = A % B;
        System.out.println("Add = " + (Add));
        System.out.println("Sub = " + (Sub));
        System.out.println("Mult = " + (Mult));
        System.out.println("Div = " + (Div));
        System.out.println("Mod = " + (Mod));
    }
}
